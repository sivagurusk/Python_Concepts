#TypeCast

#int
a=10;
print(a)
print(type(a))

#float
b=float(a)
print(b)
print(type(b))

#str
name=str(a)
print(name)
print(type(name))

#bool
is_true=bool(a)
print(is_true)
print(type(is_true))

#list
my_list=list((1,2,3,4,5))
print(my_list)
print(type(my_list))

#tuple
my_tuple=tuple(my_list)
print(my_tuple)
print(type(my_tuple))

#set
my_set=set(my_list)
print(my_set)
print(type(my_set))



